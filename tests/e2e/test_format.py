def test_formats_match_the_brief(app):
    got = app.evaluate(
        "async (cases) => { const f = await import('/format.js'); return cases.map(([fn, args]) => f[fn](...args)); }",
        [[fn, args] for fn, args, _ in CASES],
    )
    assert got == [want for *_, want in CASES]
